const fs=require('fs'),vm=require('vm'),assert=require('assert');
const file=__dirname+'/../front-end/js/book-cover.js';
assert(fs.existsSync(file),'Falta tratamento compartilhado de capas ausentes e quebradas');
const fallback='/TCC-Nook/img/livro-sem-capa.svg';
let handler,observer;
const image=(src,book=true)=>({tagName:'IMG',src,complete:true,naturalWidth:0,matches:()=>book,getAttribute(name){return name==='src'?this.src:null;},querySelectorAll:()=>[]});
const missing=image(''),broken=image('/missing.jpg'),avatar=image('/missing-avatar.jpg',false),good=image('/cover.jpg');good.naturalWidth=100;
const images=[missing,broken,avatar,good];
const document={addEventListener(name,fn){if(name==='error')handler=fn;},querySelectorAll(){return images.filter(i=>i.matches());},documentElement:{}};
vm.runInNewContext(fs.readFileSync(file,'utf8'),{document,MutationObserver:class{constructor(fn){observer=fn;}observe(){}}});
assert.equal(missing.src,fallback);assert.equal(broken.src,fallback);assert.equal(good.src,'/cover.jpg');
handler({target:avatar});assert.equal(avatar.src,'/missing-avatar.jpg');
const dynamic=image('/broken-dynamic.jpg');handler({target:dynamic});assert.equal(dynamic.src,fallback);
const added=image('');observer([{addedNodes:[added]}]);assert.equal(added.src,fallback);
handler({target:dynamic});assert.equal(dynamic.src,fallback);
console.log('PASS: capas ausentes, quebradas e dinâmicas usam a imagem Nook; avatares e capas válidas preservados');

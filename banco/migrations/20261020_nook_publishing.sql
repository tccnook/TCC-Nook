BEGIN;
CREATE TABLE IF NOT EXISTS admin (
 id_admin integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 nome_completo varchar(100), email varchar(100) UNIQUE, senha varchar(250), criacao_conta timestamp DEFAULT now()
);
DO $$ DECLARE t text; col text; seq text; max_id bigint;
BEGIN
 FOR t,col IN SELECT 'livro','id_livro' UNION ALL SELECT 'capitulo','id_capitulo' LOOP
  SELECT pg_get_serial_sequence(t,col) INTO seq;
  IF seq IS NULL THEN
   EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',t,col);
   SELECT pg_get_serial_sequence(t,col) INTO seq;
   EXECUTE format('SELECT COALESCE(MAX(%I),0) FROM %I',col,t) INTO max_id;
   PERFORM setval(seq::regclass,GREATEST(max_id,1),max_id>0);
  END IF;
 END LOOP;
END $$;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS autor_desde timestamptz;
ALTER TABLE capitulo ADD COLUMN IF NOT EXISTS conteudo_html text NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS publicacao_obra (
 id_livro integer PRIMARY KEY REFERENCES livro(id_livro),
 id_autor integer NOT NULL REFERENCES usuario(id_user),
 modalidade text NOT NULL CHECK(modalidade IN ('editor','pdf')),
 estado text NOT NULL DEFAULT 'rascunho' CHECK(estado IN ('rascunho','publicado','arquivado','excluido')),
 titulo text NOT NULL DEFAULT '', resumo text NOT NULL DEFAULT '',
 id_genero integer REFERENCES preferencia(id_preferencia), classificacao integer CHECK(classificacao IN (0,10,12,14,16,18)),
 capa_url text, pdf_rascunho text, revisao integer NOT NULL DEFAULT 1,
 atualizado_em timestamptz NOT NULL DEFAULT now(), criado_em timestamptz NOT NULL DEFAULT now(),
 retirado_em timestamptz, motivo_retirada text
);
CREATE INDEX IF NOT EXISTS publicacao_autor_estado ON publicacao_obra(id_autor,estado,atualizado_em DESC);
CREATE TABLE IF NOT EXISTS edicao_livro (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, id_livro integer NOT NULL REFERENCES livro(id_livro),
 numero integer NOT NULL CHECK(numero>0), criada_em timestamptz NOT NULL DEFAULT now(), UNIQUE(id_livro,numero)
);
CREATE TABLE IF NOT EXISTS versao_publicacao (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, id_edicao bigint NOT NULL REFERENCES edicao_livro(id),
 numero integer NOT NULL CHECK(numero>0), arquivo text NOT NULL, paginas integer NOT NULL CHECK(paginas>0),
 snapshot jsonb NOT NULL, declaracao text NOT NULL CHECK(declaracao IN ('autoria','autorizacao')),
 publicada_por integer NOT NULL REFERENCES usuario(id_user), publicada_em timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id_edicao,numero)
);
ALTER TABLE publicacao_obra ADD COLUMN IF NOT EXISTS id_versao_atual bigint REFERENCES versao_publicacao(id);
CREATE TABLE IF NOT EXISTS progresso_publicacao (
 id_user integer NOT NULL REFERENCES usuario(id_user), id_livro integer NOT NULL REFERENCES livro(id_livro),
 id_versao bigint NOT NULL REFERENCES versao_publicacao(id), pagina integer NOT NULL DEFAULT 1 CHECK(pagina>0),
 concluido_em timestamptz, atualizado_em timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(id_user,id_livro)
);
CREATE TABLE IF NOT EXISTS comentario_obra (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, id_livro integer NOT NULL REFERENCES livro(id_livro),
 id_user integer NOT NULL REFERENCES usuario(id_user), texto text NOT NULL CHECK(length(texto) BETWEEN 1 AND 3000),
 criado_em timestamptz NOT NULL DEFAULT now(), editado_em timestamptz,
 estado text NOT NULL DEFAULT 'visivel' CHECK(estado IN ('visivel','oculto','excluido'))
);
CREATE INDEX IF NOT EXISTS comentario_obra_livro ON comentario_obra(id_livro,criado_em DESC);
CREATE INDEX IF NOT EXISTS comentario_obra_usuario ON comentario_obra(id_user,criado_em DESC);
CREATE TABLE IF NOT EXISTS denuncia_obra (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, id_livro integer NOT NULL REFERENCES livro(id_livro),
 id_user integer NOT NULL REFERENCES usuario(id_user), motivo text NOT NULL CHECK(motivo IN ('plagio','direitos','inadequado','outro')),
 detalhes text NOT NULL CHECK(length(detalhes) BETWEEN 10 AND 3000),
 estado text NOT NULL DEFAULT 'aberta' CHECK(estado IN ('aberta','resolvida')),
 criada_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS denuncia_obra_estado ON denuncia_obra(estado,criada_em DESC);
CREATE TABLE IF NOT EXISTS moderacao_obra (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, id_livro integer NOT NULL REFERENCES livro(id_livro),
 id_admin integer NOT NULL REFERENCES admin(id_admin), acao text NOT NULL CHECK(acao IN ('retirar','restaurar')),
 motivo text NOT NULL, criada_em timestamptz NOT NULL DEFAULT now()
);
COMMIT;
